-- =====================================================================
-- Food Cost – Esquema de base de datos para Supabase
-- Ejecutar completo en: Supabase → SQL Editor → New query → Run
-- Se puede volver a ejecutar sin perder datos (es idempotente).
-- =====================================================================

create extension if not exists pgcrypto;

-- 1) Configuración general (una sola fila)
create table if not exists public.config (
  id          int primary key default 1 check (id = 1),
  meta        numeric not null default 30,     -- meta de food cost %
  igv         boolean not null default true,   -- precios incluyen IGV 18%
  updated_at  timestamptz not null default now()
);
insert into public.config (id) values (1) on conflict (id) do nothing;

-- 2) Insumos
create table if not exists public.insumos (
  id          uuid primary key default gen_random_uuid(),
  pos         bigint generated by default as identity,  -- orden de creación
  nombre      text not null default '',
  unidad      text not null default 'kg',
  costo       numeric not null default 0,      -- costo de compra por unidad (S/)
  merma       numeric not null default 0,      -- % de merma
  created_at  timestamptz not null default now()
);

-- 3) Recetas (platos)
create table if not exists public.recetas (
  id          uuid primary key default gen_random_uuid(),
  pos         bigint generated by default as identity,
  nombre      text not null default '',
  precio      numeric not null default 0,      -- precio de venta (S/)
  created_at  timestamptz not null default now()
);

-- 4) Ingredientes de cada receta (cantidad por porción)
create table if not exists public.receta_items (
  id          uuid primary key default gen_random_uuid(),
  receta_id   uuid not null references public.recetas(id) on delete cascade,
  insumo_id   uuid not null references public.insumos(id) on delete cascade,
  cant        numeric not null default 0,
  orden       int not null default 0
);
create index if not exists receta_items_receta_idx on public.receta_items(receta_id);
create index if not exists receta_items_insumo_idx on public.receta_items(insumo_id);

-- 5) Unidades vendidas por plato (periodo actual)
create table if not exists public.ventas (
  receta_id   uuid primary key references public.recetas(id) on delete cascade,
  unidades    numeric not null default 0
);

-- 6) Inventario por insumo (periodo actual)
create table if not exists public.inventario (
  insumo_id   uuid primary key references public.insumos(id) on delete cascade,
  ini         numeric not null default 0,
  compras     numeric not null default 0,
  fin         numeric not null default 0
);

-- =====================================================================
-- Seguridad: solo usuarios con sesión iniciada pueden leer y escribir.
-- Los visitantes anónimos no ven nada.
-- =====================================================================
grant usage on schema public to authenticated;
grant select, insert, update, delete on
  public.config, public.insumos, public.recetas,
  public.receta_items, public.ventas, public.inventario
  to authenticated;
grant usage, select on all sequences in schema public to authenticated;
revoke all on
  public.config, public.insumos, public.recetas,
  public.receta_items, public.ventas, public.inventario
  from anon;

do $$
declare t text;
begin
  foreach t in array array['config','insumos','recetas','receta_items','ventas','inventario'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "usuarios_autenticados" on public.%I', t);
    execute format(
      'create policy "usuarios_autenticados" on public.%I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;
